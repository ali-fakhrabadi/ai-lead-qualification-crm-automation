"""Request and response models of the public, operator and internal APIs."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any, Generic, Literal, TypeVar

from pydantic import BaseModel, ConfigDict, EmailStr, Field

T = TypeVar("T")


class Page(BaseModel, Generic[T]):  # noqa: UP046 - explicit Generic keeps pydantic happy
    items: list[T]
    total: int
    limit: int
    offset: int


class ORM(BaseModel):
    model_config = ConfigDict(from_attributes=True)


# --- intake ----------------------------------------------------------------------------------
class LeadSubmission(BaseModel):
    """What a lead submits. Strings are length-limited; normalization happens server side."""

    model_config = ConfigDict(extra="forbid")

    first_name: str = Field(min_length=1, max_length=100)
    last_name: str = Field(min_length=1, max_length=100)
    email: str = Field(min_length=3, max_length=320)
    company: str | None = Field(None, max_length=200)
    website: str | None = Field(None, max_length=253)
    job_title: str | None = Field(None, max_length=120)
    country: str | None = Field(None, max_length=80)
    interest: str = Field(min_length=2, max_length=60)
    message: str = Field(min_length=20, max_length=4000)
    consent_contact: bool
    consent_marketing: bool = False


class PublicLeadForm(LeadSubmission):
    # Generated by the form when it loads: a double submit is recognised as the same event.
    submission_id: str | None = Field(None, pattern=r"^[A-Za-z0-9_-]{16,64}$")
    # Honeypot: hidden from people; bots fill it in. A filled value is accepted and dropped.
    nickname: str | None = Field(None, max_length=200)


class WebhookLeadEvent(BaseModel):
    model_config = ConfigDict(extra="forbid")

    event_id: str = Field(pattern=r"^[A-Za-z0-9._:-]{8,100}$")
    occurred_at: datetime | None = None
    lead: LeadSubmission


class IntakeResponse(BaseModel):
    status: Literal["accepted", "duplicate"]
    outcome: str
    lead_reference: str
    correlation_id: str
    replayed: bool = False


class FormOption(BaseModel):
    value: str
    label: str


class FormConfig(BaseModel):
    business_name: str
    interests: list[FormOption]
    required_fields: list[str]
    consent_text: str
    consent_text_version: str


# --- auth ----------------------------------------------------------------------------------
class LoginRequest(BaseModel):
    email: EmailStr
    password: str = Field(min_length=1, max_length=200)


class RefreshRequest(BaseModel):
    refresh_token: str = Field(min_length=10, max_length=200)


class TokenResponse(BaseModel):
    access_token: str
    refresh_token: str
    token_type: str = "bearer"  # noqa: S105 - the OAuth token type, not a secret
    expires_in: int


class MeOut(BaseModel):
    id: uuid.UUID
    email: str
    full_name: str
    role: str


class UserCreate(BaseModel):
    email: EmailStr
    full_name: str = Field("", max_length=200)
    password: str = Field(min_length=12, max_length=200)
    role: Literal["admin", "operator", "viewer"]


class UserUpdate(BaseModel):
    role: Literal["admin", "operator", "viewer"] | None = None
    is_active: bool | None = None


class UserOut(ORM):
    id: uuid.UUID
    email: str
    full_name: str
    role: str
    is_active: bool
    created_at: datetime
    last_login_at: datetime | None


# --- leads -----------------------------------------------------------------------------------
class LeadListItem(ORM):
    id: uuid.UUID
    reference: str
    status: str
    first_name: str
    last_name: str
    email: str
    company: str | None
    interest: str
    source: str
    decision: str | None
    score: int | None
    intent_category: str | None
    review_reasons: list[str]
    created_at: datetime
    last_event_at: datetime


class EventOut(ORM):
    id: uuid.UUID
    source: str
    channel: str
    outcome: str
    correlation_id: str
    received_at: datetime
    occurred_at: datetime | None
    replay_count: int
    payload: dict[str, Any]


class AssessmentOut(ORM):
    id: uuid.UUID
    provider: str
    model: str
    status: str
    error: str | None
    parsed: dict[str, Any] | None
    rules: dict[str, Any] | None
    decision: str | None
    score: int | None
    latency_ms: int | None
    superseded: bool
    override_decision: str | None
    override_reason: str | None
    overridden_at: datetime | None
    created_at: datetime


class DuplicateOut(ORM):
    id: uuid.UUID
    kind: str
    lead_id: uuid.UUID
    candidate_lead_id: uuid.UUID | None
    reasons: list[str]
    proposed: dict[str, Any]
    status: str
    note: str | None
    resolved_at: datetime | None
    created_at: datetime


class DuplicateWithLeads(DuplicateOut):
    lead: LeadListItem
    candidate: LeadListItem | None


class CrmSyncOut(ORM):
    provider: str
    status: str
    remote_contact_id: str | None
    remote_company_id: str | None
    attempts: int
    last_error_code: str | None
    last_error: str | None
    synced_at: datetime | None
    updated_at: datetime


class DraftOut(ORM):
    id: uuid.UUID
    lead_id: uuid.UUID
    version: int
    subject: str
    body: str
    generated_by: str
    model: str | None
    status: str
    edited_at: datetime | None
    decided_at: datetime | None
    decision_note: str | None
    delivery_channel: str | None
    delivered_at: datetime | None
    delivery_error: str | None
    created_at: datetime


class WorkflowEventOut(ORM):
    id: uuid.UUID
    event_type: str
    lead_id: uuid.UUID | None
    status: str
    attempts: int
    last_error: str | None
    correlation_id: str
    created_at: datetime
    dispatched_at: datetime | None
    completed_at: datetime | None
    workflow_execution_id: str | None
    workflow_status: str | None
    workflow_duration_ms: int | None


class AuditOut(ORM):
    id: int
    ts: datetime
    actor_type: str
    actor_email: str | None = None
    action: str
    outcome: str
    lead_id: uuid.UUID | None
    correlation_id: str | None
    details: dict[str, Any]


class LeadDetail(LeadListItem):
    website: str | None
    company_domain: str | None
    job_title: str | None
    country: str | None
    message: str
    consent_contact: bool
    consent_marketing: bool
    retry_stage: str | None
    qualified_at: datetime | None
    synced_at: datetime | None
    events: list[EventOut]
    assessments: list[AssessmentOut]
    duplicates: list[DuplicateOut]
    crm: CrmSyncOut | None
    drafts: list[DraftOut]
    workflow_events: list[WorkflowEventOut]


class OverrideRequest(BaseModel):
    decision: Literal["qualified", "needs_review", "unqualified"]
    reason: str = Field(min_length=3, max_length=500)


class ReasonRequest(BaseModel):
    reason: str = Field(min_length=3, max_length=500)


class DuplicateResolve(BaseModel):
    resolution: Literal["kept_separate", "same_person", "update_applied", "dismissed"]
    note: str | None = Field(None, max_length=500)


class DraftEdit(BaseModel):
    subject: str = Field(min_length=3, max_length=200)
    body: str = Field(min_length=10, max_length=5000)


class DraftDecision(BaseModel):
    note: str | None = Field(None, max_length=500)


class Stats(BaseModel):
    by_status: dict[str, int]
    by_decision: dict[str, int]
    open_duplicates: int
    drafts_awaiting_review: int
    events_pending: int
    events_failed: int
    leads_total: int


# --- internal (n8n) ----------------------------------------------------------------------------
class StepResult(BaseModel):
    lead_id: uuid.UUID
    status: str
    next: Literal["crm_sync", "follow_up_draft", "stop", "deliver", "done"]
    detail: dict[str, Any] = {}


class OutcomeReport(BaseModel):
    execution_id: str = Field(max_length=40)
    status: Literal["success", "error", "stopped"]
    step: str | None = Field(None, max_length=40)
    duration_ms: int | None = Field(None, ge=0)
    error: str | None = Field(None, max_length=300)


class ExecutionStarted(BaseModel):
    execution_id: str = Field(max_length=40)


class WorkflowError(BaseModel):
    execution_id: str | None = Field(None, max_length=40)
    workflow: str | None = Field(None, max_length=120)
    node: str | None = Field(None, max_length=120)
    message: str | None = Field(None, max_length=300)
    event_id: uuid.UUID | None = None
    lead_id: uuid.UUID | None = None


class FaultRuleIn(BaseModel):
    target: Literal["llm"]
    mode: Literal["malformed", "unavailable"]
    email: EmailStr
    remaining: int = Field(1, ge=1, le=100)
